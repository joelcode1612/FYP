-- =====================================================================
-- 20261125_07 — publisher read of the Section B inputs
--
-- Why this migration exists
--   ``20261125_02`` created ``p1_cq_publisher`` and granted it SELECT on the
--   five M2 tables the *binding comparison* reads; ``20261125_03`` added the
--   build receipt. Both are already applied and applied history is immutable
--   here, so the publisher's read set is extended in a new migration.
--
-- Why the tables are needed at all
--   Section B of the questionnaire is the set of approved additional questions
--   generated by Direct-QG. Before this change the publisher composed only the
--   13 governed core items and never called
--   ``services.questionnaire_composition.compose``, so an additional question
--   could not reach a release no matter how many had been approved. The
--   composer needs three things the publisher could not read:
--
--     * ``m2_qg_candidates``           — the generated question, its options,
--                                        validation statuses and revision;
--     * ``m2_qg_candidate_reviews``    — the owner's APPROVE_FOR_REVIEW/REJECT
--                                        decision, without which no candidate
--                                        is eligible;
--     * ``m2_bdj_objective_admissions``/``m2_bdj_objective_decisions``/
--       ``m2_bdj_objective_proposals`` — the objective authority, read only to
--                                        report whether Section B is empty
--                                        because nothing was authorised or
--                                        because nothing eligible was approved.
--
--   None of these is respondent evidence. They are the owner's own
--   question-design records, which is exactly the class of input the publisher
--   already reads (``m2_assessments``, ``m2_answer_revisions``,
--   ``m2_confirmation_snapshots``, ``m2_business_contexts``).
--
-- What is granted
--   SELECT, on five tables, to one role. Every one of those tables already
--   carries its ``owner_scope`` policy ``TO public`` on ``project1_actor()`` /
--   ``project1.actor_id``, so the publisher sees the rows of the actor it is
--   bound to and no others. No policy is created or altered, and no other
--   principal moves. The publisher still holds no INSERT, UPDATE or DELETE
--   anywhere, so publication cannot mint or edit a candidate or a review.
--
-- Explicit operator execution only. Never run at startup.
-- =====================================================================
BEGIN;
SET LOCAL lock_timeout = '5s';

DO $$ BEGIN
  IF current_setting('project1.cq_migration_target', true) IS DISTINCT FROM current_database()
     OR nullif(current_setting('project1.cq_migration_receipt', true), '') IS NULL
     OR coalesce(current_setting('project1.cq_migration_sha256', true), '') !~ '^[0-9a-f]{64}$' THEN
    RAISE EXCEPTION 'Explicit target, receipt and hash required';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'p1_cq_publisher') THEN
    RAISE EXCEPTION 'p1_cq_publisher missing: apply 20261125_02 first';
  END IF;
  IF to_regclass('public.m2_qg_candidates') IS NULL
     OR to_regclass('public.m2_qg_candidate_reviews') IS NULL
     OR to_regclass('public.m2_bdj_objective_admissions') IS NULL
     OR to_regclass('public.m2_bdj_objective_decisions') IS NULL
     OR to_regclass('public.m2_bdj_objective_proposals') IS NULL THEN
    RAISE EXCEPTION 'a Section B input table is missing';
  END IF;
  IF EXISTS (SELECT 1 FROM cq_schema_migrations
              WHERE version = '20261125_07'
                AND migration_sha256 <> current_setting('project1.cq_migration_sha256')) THEN
    RAISE EXCEPTION 'Migration hash differs';
  END IF;
END $$;

GRANT SELECT ON public.m2_qg_candidates           TO p1_cq_publisher;
GRANT SELECT ON public.m2_qg_candidate_reviews    TO p1_cq_publisher;
GRANT SELECT ON public.m2_bdj_objective_admissions TO p1_cq_publisher;
GRANT SELECT ON public.m2_bdj_objective_decisions TO p1_cq_publisher;
GRANT SELECT ON public.m2_bdj_objective_proposals TO p1_cq_publisher;

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['m2_qg_candidates', 'm2_qg_candidate_reviews',
                           'm2_bdj_objective_admissions', 'm2_bdj_objective_decisions',
                           'm2_bdj_objective_proposals'] LOOP
    IF NOT has_table_privilege('p1_cq_publisher', 'public.' || t, 'SELECT') THEN
      RAISE EXCEPTION 'publisher cannot read %', t;
    END IF;
    IF has_table_privilege('p1_cq_publisher', 'public.' || t, 'INSERT')
       OR has_table_privilege('p1_cq_publisher', 'public.' || t, 'UPDATE')
       OR has_table_privilege('p1_cq_publisher', 'public.' || t, 'DELETE') THEN
      RAISE EXCEPTION 'publisher must not write %', t;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies
                    WHERE schemaname = 'public' AND tablename = t
                      AND policyname = 'owner_scope' AND cmd = 'ALL') THEN
      RAISE EXCEPTION 'owner_scope policy on % changed shape', t;
    END IF;
  END LOOP;
END $$;

INSERT INTO cq_schema_migrations(version, migration_sha256, receipt)
VALUES ('20261125_07', current_setting('project1.cq_migration_sha256'),
        current_setting('project1.cq_migration_receipt'))
ON CONFLICT (version) DO NOTHING;

COMMIT;
