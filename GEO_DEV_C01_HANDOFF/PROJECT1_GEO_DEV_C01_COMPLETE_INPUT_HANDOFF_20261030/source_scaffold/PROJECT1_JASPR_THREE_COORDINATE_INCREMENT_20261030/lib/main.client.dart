/// Project1 research demonstrator entrypoint (NOT connected to real Project1).
import 'dart:async';
import 'dart:convert';
import 'dart:js_interop';
import 'package:jaspr/client.dart';
import 'package:jaspr/dom.dart';
import 'geometry_contract.dart';
import 'synthetic_rentals.dart';
import 'main.client.options.dart'; // Generated by Jaspr CLI during serve/build.

@JS('project1MapUpdate')
external void project1MapUpdate(JSString jsonPayload);

void main() {
  // Standalone client-mode Jaspr. The official Jaspr CLI generates this options
  // file when run; do not claim it has been generated in this sandbox.
  Jaspr.initializeApp(options: defaultClientOptions);
  runApp(const GeoReportDemo(), attachTo: '#app');
}

class GeoReportDemo extends StatefulComponent {
  const GeoReportDemo({super.key});
  @override
  State<GeoReportDemo> createState() => _GeoReportDemoState();
}

class _GeoReportDemoState extends State<GeoReportDemo> {
  final rentals = syntheticRentalCentres;
  String selectedId = 'SYN-A';
  int demoRadius = 800; // Illustrative preview, explicitly NOT ODR-3a adopted.
  bool showGeometryPreview = true;
  bool reportView = false;

  RentalCentre get selected => rentals.firstWhere((r) => r.rentalId == selectedId);

  void syncMap() {
    final r = selected;
    final decision = classifyCentre(r);
    final payload = {
      'rentalId': r.rentalId, 'synthetic': true,
      'lat': decision.canDraw ? r.latitude : null,
      'lng': decision.canDraw ? r.longitude : null,
      'radius': decision.canDraw && showGeometryPreview ? demoRadius : null,
      'label': r.label,
      'rentals': rentals.map((candidate) {
        final eligible = classifyCentre(candidate).canDraw;
        return {
          'id': candidate.rentalId,
          'label': candidate.label,
          'synthetic': candidate.synthetic,
          'lat': eligible ? candidate.latitude : null,
          'lng': eligible ? candidate.longitude : null,
        };
      }).toList(),
    };
    project1MapUpdate(jsonEncode(payload).toJS);
  }

  @override
  void initState() {
    super.initState();
    // The map's HTML container must exist before Leaflet can attach.
    Future<void>.delayed(const Duration(milliseconds: 150), syncMap);
  }

  @override
  Component build(BuildContext context) {
    final r = selected;
    final centre = classifyCentre(r);
    final state = centre.canDraw ? CompetitorState.s1 : CompetitorState.s3;
    final message = absenceBody(state);
    return div(classes: 'app-shell', [
      header(classes: 'topbar', [
        div(classes: 'topbar-brand', [
          span(classes: 'brandmark', [.text('P1')]),
          div([
            strong([.text('PROJECT1')]),
            small([.text('GEOGRAPHIC EVIDENCE • JASPR DEMO')]),
          ]),
        ]),
        span(classes: 'topbar-pill', [.text('SYNTHETIC ONLY · NO REPORT APPROVAL')]),
      ]),
      main_([ // Jaspr avoids collision with Dart's main() using main_.
        section(classes: 'intro', [
          p(classes: 'eyebrow', [.text('Café planning / contextual evidence')]),
          h1([.text('Understand the geography behind your café assessment')]),
          p([.text('Three synthetic coordinate fixtures on an OpenStreetMap basemap, experimental geometry, and one combined report preview. No rental or competitor observation is real.')]),
        ]),
        div(classes: 'tabs', [
          button(classes: reportView ? 'tab' : 'tab selected', onClick: () {
            setState(() => reportView = false);
            Future<void>.delayed(const Duration(milliseconds: 80), syncMap);
          }, [.text('Map & geometry')]),
          button(classes: reportView ? 'tab selected' : 'tab', onClick: () => setState(() => reportView = true), [.text('Report preview')]),
        ]),
        if (!reportView) div(classes: 'columns', [
          aside(classes: 'sidepanel', [
            h2([.text('Selected rental')]),
            p(classes: 'muted', [.text('Three fictional coordinates are shown on the map. The real selection UI belongs to your teammate.')]),
            for (final item in rentals)
              button(classes: item.rentalId == selectedId ? 'rental active' : 'rental', onClick: () {
                setState(() => selectedId = item.rentalId);
                syncMap();
              }, [
                strong([.text(item.label)]),
                small([.text('SYNTHETIC coordinate • not a verified rental')]),
              ]),
            h3([.text('Geometry experiment')]),
            p(classes: 'muted', [.text('ODR-3a remains UNDECIDED. These radii demonstrate sensitivity only.')]),
            div(classes: 'radius-row', [
              for (final n in [400, 500, 800, 1200])
                button(classes: demoRadius == n ? 'radius active' : 'radius', onClick: () {
                  setState(() { demoRadius = n; showGeometryPreview = true; });
                  syncMap();
                }, [.text('${n}m')]),
            ]),
            button(classes: 'toggle', onClick: () {
              setState(() => showGeometryPreview = !showGeometryPreview);
              syncMap();
            }, [.text(showGeometryPreview ? 'Hide experimental circle' : 'Show experimental circle')]),
            p(classes: 'muted', [.text('Spherical haversine, Earth radius 6,371,000 m. Proposed boundary tolerance: 0.5 m (not adopted).')]),
          ]),
          section(classes: 'map-panel', [
            div(classes: 'map-heading', [
              h2([.text('Rental context map')]),
              span(classes: 'note-pill', [.text('OSM basemap ≠ competitor dataset')]),
            ]),
            div(id: 'geo-map', classes: 'map-view', []),
            div(classes: 'caption', [.text(centre.canDraw
              ? 'All three synthetic rental markers are shown. The selected marker has an EXPERIMENTAL straight-line circle; no radius has been adopted.'
              : 'Area-only records cannot produce a precise rental footprint; no circle or measured distance is shown.')]),
            div(classes: 'evidence-card', [
              h3([.text('Nearby-business evidence')]),
              p(classes: 'status', [.text(state == CompetitorState.s1 ? 'SOURCE UNAVAILABLE' : 'NOT QUERIED')]),
              p([.text(message)]),
              div(classes: 'provenance', [
                strong([.text('Provenance and scope')]),
                p([.text('No competitor dataset connected. No rights adjudication. No collection or query date. Nothing in the basemap is being treated as a competitor observation.')]),
              ]),
            ]),
          ]),
        ]) else section(classes: 'report', [
          h2([.text('One assessment — shared geographic report preview')]),
          div(classes: 'report-block', [
            h3([.text('Selected rental references (synthetic only)')]),
            for (final candidate in rentals)
              p([.text('${candidate.rentalId}: ${candidate.label}; competitor data unavailable (no dataset or source rights established).')]),
          ]),
          h2([.text('R09 — Selected rental geographic competitor context')]),
          p(classes: 'muted', [.text('Illustrative report section for ${r.label}; no production output.')]),
          div(classes: 'report-block', [
            h3([.text('Premises geographic status')]),
            p([.text(centre.explanation)]),
            p([.text('Location class: ${r.kind.name}. Locality: ${r.locality}.')]),
          ]),
          div(classes: 'report-block', [
            h3([.text('Competitor evidence state')]),
            p(classes: 'status', [.text(state == CompetitorState.s1 ? 'COMPETITOR_DATA_UNAVAILABLE' : 'COMPETITORS_NOT_QUERIED_ZONE_UNRESOLVED')]),
            p([.text(message)]),
            h4([.text('Separate provenance')]),
            p([.text('The source, query time, observation date, usage rights and coverage remain unverified. Do not interpret unavailable data as zero businesses.')]),
          ]),
          div(classes: 'report-block', [
            h3([.text('Geographic interpretation limits')]),
            p([.text('Straight-line geometry does not measure walking time, demand, saturation, suitability or comparative advantage. The report cannot issue a numerical site score.')]),
          ]),
          p(classes: 'caption', [.text('R01 administrative area is separate from the rental-specific circle. Cross-candidate business counts are forbidden until E-1, E-2 and E-3 can be demonstrated.')]),
        ]),
      ]),
      footer([.text('Project1 experimental geometry/report demonstrator · Existing application, scientific and production approvals unchanged.')]),
    ]);
  }
}
