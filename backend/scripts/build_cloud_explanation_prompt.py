def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    prompt_md = build_prompt_md()
    (OUT / 'PROJECT1_CLOUD_EXPLANATION_PROMPT_V1_CANDIDATE.md').write_text(
        prompt_md, encoding='utf-8')
    contract = build_request_contract()
    (OUT / 'PROJECT1_CLOUD_EXPLANATION_REQUEST_CONTRACT.json').write_text(
        json.dumps(contract, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    matrix = build_test_matrix()
    (OUT / 'PROJECT1_CLOUD_EXPLANATION_TEST_MATRIX.json').write_text(
        json.dumps(matrix, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')

    import hashlib
    for name in ('PROJECT1_CLOUD_EXPLANATION_PROMPT_V1_CANDIDATE.md',
                 'PROJECT1_CLOUD_EXPLANATION_REQUEST_CONTRACT.json',
                 'PROJECT1_CLOUD_EXPLANATION_TEST_MATRIX.json'):
        raw = (OUT / name).read_bytes()
        print(f'{name}  {len(raw):>8} bytes  {hashlib.sha256(raw).hexdigest()}')


if __name__ == '__main__':
    main()
