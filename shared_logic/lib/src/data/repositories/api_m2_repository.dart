/// Read-only, owner and confirmation-bound BDJ result; origin is not inferred.
final class CurrentBdjResult {
  final String status;
  final List<Map<String, dynamic>> findings;
  const CurrentBdjResult._(this.status, this.findings);

  factory CurrentBdjResult.parse(
    Map<String, dynamic> data,
    String assessment,
    String confirmation,
    int revision,
  ) {
    const statuses = {
      'NO_CURRENT_RESULT',
      'UNKNOWN_OUTCOME',
      'STALE_RESULT',
      'VALIDATION_FAILED',
      'COMPLETED_WITH_FINDINGS',
      'COMPLETED_ZERO_FINDINGS',
      'RESULT_UNAVAILABLE',
    };
    final status = data['status'];
    if (data['contract_version'] != 'sitewise-bdj-current/1' ||
        data['assessment_id'] != assessment ||
        data['confirmation_id'] != confirmation ||
        data['assessment_revision'] != revision ||
        !statuses.contains(status) ||
        data['source_fingerprint'] is! String ||
        !RegExp(
          r'^[a-f0-9]{64}$',
        ).hasMatch(data['source_fingerprint'] as String)) {
      throw const FormatException('BDJ result source binding mismatch.');
    }
    final result = data['result'];
    if (status == 'COMPLETED_ZERO_FINDINGS' ||
        status == 'COMPLETED_WITH_FINDINGS') {
      if (result is! Map ||
          result['assessment_id'] != assessment ||
          result['assessment_revision'] != revision ||
          result['source_fingerprint'] != data['source_fingerprint'] ||
          result['validation_status'] != 'valid' ||
          result['finding_authority'] != 'candidate_only' ||
          result['findings'] is! List) {
        throw const FormatException('BDJ result is not verified.');
      }
      final findings = (result['findings'] as List).map((row) {
        if (row is! Map ||
            row['observed_condition'] is! String ||
            row['rule_id'] is! String) {
          throw const FormatException('BDJ finding is invalid.');
        }
        return Map<String, dynamic>.unmodifiable(
          Map<String, dynamic>.from(row),
        );
      }).toList();
      if ((status == 'COMPLETED_ZERO_FINDINGS') != findings.isEmpty ||
          result['finding_count'] != findings.length) {
        throw const FormatException('BDJ finding count mismatch.');
      }
      return CurrentBdjResult._(status as String, List.unmodifiable(findings));
    }
    if (result != null)
      throw const FormatException('Non-current BDJ result supplied.');
    return CurrentBdjResult._(status as String, const []);
  }
}

/// Byte-for-byte port of Python's `json.dumps(value, sort_keys=True,
/// ensure_ascii=False, separators=(",", ":"), allow_nan=False)`.
///
/// The server hashes with that exact call (`project1.contracts.canonical`,
/// `services.business_context_v1.source_hash`, `services.m2_service` snapshot
/// digest). Dart's `jsonEncode` is *not* equivalent for doubles: it prints
/// `1e-6` as `0.000001` and `1e16` as `10000000000000000.0`, where Python
/// prints `1e-06` and `1e+16`. Recomputing a server digest with `jsonEncode`
/// therefore rejected valid snapshots (UI-07). Every double is routed through
/// [_pythonDoubleRepr]; ints, strings, bools, null and containers already
/// agree with Python.
///
/// Equivalence is proven against a corpus generated by the Python
/// implementation itself — see `test/m2_canonical_equivalence_test.dart`.
String canonicalSourceJson(Object? value) {
  if (value is Map) {
    final keys = value.keys.map((k) {
      if (k is! String) {
        throw ArgumentError(
          'JSON object keys must be strings, got ${k.runtimeType}.',
        );
      }
      return k;
    }).toList()..sort();
    return '{${keys.map((k) => '${jsonEncode(k)}:${canonicalSourceJson(value[k])}').join(',')}}';
  }
  if (value is List) return '[${value.map(canonicalSourceJson).join(',')}]';
  if (value is double) return _pythonDoubleRepr(value);
  return jsonEncode(value);
}

/// M2 confirmation revisions are integral in the server contract. On dart2js
/// JSON integers may also satisfy `is double`; preserve this known field as an
/// integer without changing float formatting for BCB or other source packets.
String canonicalConfirmationJson(Map<String, dynamic> snapshot) {
  final keys = snapshot.keys.toList()..sort();
  return '{${keys.map((key) => '${jsonEncode(key)}:${key == 'assessment_revision' && snapshot[key] is int ? jsonEncode(snapshot[key]) : canonicalSourceJson(snapshot[key])}').join(',')}}';
}

/// BCB revision fields are integers in both approved packet schemas. Preserve
/// their JSON representation on dart2js without reclassifying actual floats.
String canonicalBusinessContextJson(Object? value, [String path = '']) {
  if (value is Map) {
    final keys = value.keys.map((key) {
      if (key is! String)
        throw ArgumentError('JSON object keys must be strings.');
      return key;
    }).toList()..sort();
    return '{${keys.map((key) => '${jsonEncode(key)}:${canonicalBusinessContextJson(value[key], '$path/$key')}').join(',')}}';
  }
  if (value is List) {
    return '[${value.asMap().entries.map((e) => canonicalBusinessContextJson(e.value, '$path/${e.key}')).join(',')}]';
  }
  if (const {
        '/access/scope/confirmed_revision',
        '/concept/assessment_revision',
        '/confirmation/revision',
      }.contains(path) &&
      value is int) {
    return jsonEncode(value);
  }
  return canonicalSourceJson(value);
}

/// Python `repr(float)` / `json.dumps` float formatting.
///
/// Python uses the shortest round-trip digits (as Dart's
/// `toStringAsExponential` does) and switches to exponential notation when
/// `decpt <= -4 || decpt > 16`, padding the exponent to at least two digits.
String _pythonDoubleRepr(double value) {
  if (value.isNaN || value.isInfinite) {
    // `allow_nan=False` in Python raises here too.
    throw ArgumentError('Out of range float values are not JSON compliant.');
  }
  if (value == 0.0) return value.isNegative ? '-0.0' : '0.0';

  final negative = value.isNegative;
  final abs = value.abs();
  final exponential = abs.toStringAsExponential(); // e.g. "1.2345e+9"
  final eIndex = exponential.indexOf('e');
  final mantissa = exponential.substring(0, eIndex);
  final exponent = int.parse(exponential.substring(eIndex + 1));

  var digits = mantissa.replaceFirst('.', '');
  // Shortest form never needs trailing zeros, but normalise defensively.
  while (digits.length > 1 && digits.endsWith('0')) {
    digits = digits.substring(0, digits.length - 1);
  }

  final decpt = exponent + 1;
  final String body;
  if (decpt <= -4 || decpt > 16) {
    final sign = exponent < 0 ? '-' : '+';
    final magnitude = exponent.abs().toString().padLeft(2, '0');
    final rest = digits.length > 1 ? '.${digits.substring(1)}' : '';
    body =
        '${digits[0]}$rest'
        'e$sign$magnitude';
  } else if (decpt <= 0) {
    body = '0.${'0' * -decpt}$digits';
  } else if (decpt >= digits.length) {
    body = '$digits${'0' * (decpt - digits.length)}.0';
  } else {
    body = '${digits.substring(0, decpt)}.${digits.substring(decpt)}';
  }
  return negative ? '-$body' : body;
}

/// Existing persisted BCB envelope. A verified hash is not a research grant.
Object? _freezeSource(Object? value) => value is Map<String, dynamic>
    ? Map<String, dynamic>.unmodifiable(
        value.map((k, v) => MapEntry(k, _freezeSource(v))),
      )
    : value is List
    ? List<dynamic>.unmodifiable(value.map(_freezeSource))
    : value;

final class M2BusinessContext {
  final Map<String, dynamic> data;
  M2BusinessContext._(this.data);
  factory M2BusinessContext.parse(
    Map<String, dynamic> d,
    String assessmentId,
    String confirmationId,
    int revision,
  ) {
    final packet = d['packet'] as Map<String, dynamic>;
    final body = {...packet}..remove('packet_hash');
    final hash = sha256
        .convert(utf8.encode(canonicalBusinessContextJson(body)))
        .toString();
    if (d['contract_version'] != 'persisted-business-context/1' ||
        d['assessment_id'] != assessmentId ||
        d['confirmation_id'] != confirmationId ||
        d['assessment_revision'] != revision ||
        d['lifecycle_status'] != 'PERSISTED' ||
        !ApiM2Repository._uuid.hasMatch(d['context_id'] as String? ?? '') ||
        d['replayed'] is! bool ||
        DateTime.tryParse(d['created_at'] as String? ?? '') == null ||
        d['qj_execution_authorized'] != false ||
        d['qg_execution_authorized'] != false ||
        ![
          'business-context-package/1.0',
          'business-context-package/1.1',
        ].contains(packet['schema_version']) ||
        (packet['schema_version'] == 'business-context-package/1.1' &&
            packet['geography'] != null) ||
        packet['identity']['assessment_id'] != assessmentId ||
        packet['confirmation']['id'] != confirmationId ||
        packet['confirmation']['revision'] != revision ||
        packet['confirmation']['status'] != 'CURRENT_CONFIRMED' ||
        packet['packet_hash'] != hash ||
        packet['permissions'] is! Map ||
        packet['permissions']['qj_execution'] != false ||
        packet['permissions']['qg_execution'] != false ||
        (packet['permissions'] as Map).values.any((v) => v != false)) {
      throw const FormatException(
        'Business context source, digest or authority mismatch.',
      );
    }
    return M2BusinessContext._(_freezeSource(d) as Map<String, dynamic>);
  }
  String get id => data['context_id'] as String;
}

String m2RequestId() {
  final r = Random.secure(), b = List<int>.filled(16, 0);
  for (var i = 0; i < b.length; i++) {
    b[i] = r.nextInt(256);
  }
  b[6] = (b[6] & 15) | 64;
  b[8] = (b[8] & 63) | 128;
  final h = b.map((x) => x.toRadixString(16).padLeft(2, '0')).join();
  return '${h.substring(0, 8)}-${h.substring(8, 12)}-${h.substring(12, 16)}-${h.substring(16, 20)}-${h.substring(20)}';
}

final class M2Draft {
  final Map<String, dynamic> data;
  M2Draft._(this.data);
  factory M2Draft.fromJson(Map<String, dynamic> d, {String? assessmentId}) {
    final a = d['assessment'] as Map<String, dynamic>;
    final instrument = d['instrument'] as Map<String, dynamic>;
    final items = (d['items'] as List).cast<Map<String, dynamic>>();
    if (a['id'] != assessmentId ||
        a['revision'] is! int ||
        a['instrument_id'] != instrument['id'] ||
        items.isEmpty ||
        items.any((q) => q['instrument_id'] != a['instrument_id']) ||
        items.map((q) => q['item_key']).toSet().length != items.length) {
      throw const FormatException(
        'The saved M2 instrument and assessment bindings could not be verified.',
      );
    }
    final byKey = {for (final q in items) q['item_key']: q};
    for (final e in (d['answers'] as Map<String, dynamic>).entries) {
      final answer = e.value as Map<String, dynamic>, q = byKey[e.key];
      if (q == null ||
          answer['assessment_id'] != a['id'] ||
          answer['item_version_id'] != q['id'] ||
          (answer['assessment_revision'] as int) > (a['revision'] as int)) {
        throw const FormatException(
          'Saved answer versions do not match this M2 assessment.',
        );
      }
    }
    return M2Draft._(d);
  }
  String get id => data['assessment']['id'] as String;
  int get revision => data['assessment']['revision'] as int;
  List<Map<String, dynamic>> get items =>
      (data['items'] as List).cast<Map<String, dynamic>>();
  Map<String, dynamic> get answers => data['answers'] as Map<String, dynamic>;
}

/// Initial M2 entry uses persisted drafts. Confirmation is a separate later
/// action and is never a prerequisite for list/open/save/source projection.
final class ApiM2Repository {
  final ApiClient client;
  const ApiM2Repository(this.client);
  static final _uuid = RegExp(
    r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$',
  );
  void _id(String id) {
    if (!_uuid.hasMatch(id))
      throw const FormatException(
        'A persisted M2 assessment or instrument is required.',
      );
  }

  Future<List<Map<String, dynamic>>> _list(
    String resource,
    String contract,
  ) async {
    final d = await client.get(
      '/api/v1/m2/$resource',
      query: {'limit': '50', 'offset': '0'},
    );
    if (d['contract_version'] != contract)
      throw const FormatException('M2 catalogue is unavailable.');
    return (d['items'] as List).cast<Map<String, dynamic>>();
  }

  Future<List<Map<String, dynamic>>> instruments() =>
      _list('instruments', 'm2-instrument-list/1');
  Future<List<Map<String, dynamic>>> assessments() =>
      _list('assessments', 'm2-assessment-list/1');

  /// CP-10F: the active M2 assessment linked to a marketplace assessment.
  ///
  /// Returns `null` when no link exists — the service answers 404
  /// `ASSESSMENT_NOT_LINKED`, which is a normal state, not an error. Every other
  /// failure propagates so the UI can show it instead of pretending.
  Future<Map<String, dynamic>?> linkForMarketplace(String assessmentId) async {
    _id(assessmentId);
    try {
      return _linkPayload(
        await client.get('/api/v1/m2/assessments/by-marketplace/$assessmentId'),
        assessmentId,
      );
    } on AppFailure catch (failure) {
      if (failure.statusCode == 404) return null;
      rethrow;
    }
  }

  /// Resolve, or create once, the M2 assessment for a marketplace assessment.
  /// Idempotent: a repeat call returns the same M2 assessment with
  /// `created: false`. Creates no campaign and no downstream research artefact.
  Future<Map<String, dynamic>> initializeForMarketplace(
    String assessmentId,
  ) async {
    _id(assessmentId);
    return _linkPayload(
      await client.post(
        '/api/v1/m2/assessments/by-marketplace/$assessmentId/link',
        const <String, dynamic>{},
      ),
      assessmentId,
    );
  }

  static Map<String, dynamic> _linkPayload(
    Map<String, dynamic> payload,
    String expectedAssessmentId,
  ) {
    final m2 = payload['m2_assessment_id'];
    if (m2 is! String || !_uuid.hasMatch(m2)) {
      throw const FormatException(
        'The link response carried no M2 assessment id.',
      );
    }
    if (payload['marketplace_assessment_id'] != expectedAssessmentId) {
      throw const FormatException(
        'The link response named a different assessment.',
      );
    }
    return payload;
  }

  Future<M2Draft> read(String id) async {
    _id(id);
    return M2Draft.fromJson(
      await client.get('/api/v1/m2/assessments/$id'),
      assessmentId: id,
    );
  }

  /// Deterministic draft concept preview for the current saved revision.
  ///
  /// Read-only by contract. The response must identify itself as a draft and
  /// must deny both side effects; a server that reported otherwise would be
  /// contradicting the endpoint's purpose, so the client refuses it rather than
  /// rendering a preview that might have written a confirmation.
  Future<Map<String, dynamic>> conceptPreview(String id, int revision) async {
    _id(id);
    final body = await client.get(
      '/api/v1/m2/assessments/$id/concept-preview?expected_revision=$revision',
    );
    if (body['status'] != 'DRAFT_PREVIEW') {
      throw const FormatException(
        'The concept preview was not identified as a draft preview.',
      );
    }
    if (body['creates_confirmation'] != false ||
        body['creates_business_context'] != false) {
      throw const FormatException(
        'The concept preview reported a side effect it must never have.',
      );
    }
    return body;
  }

  Future<M2Draft> create(String instrumentId) async {
    _id(instrumentId);
    final a = await client.post('/api/v1/m2/assessments', {
      'instrument_version_id': instrumentId,
    });
    final draft = await read(a['id'] as String);
    if (draft.data['instrument']['id'] != instrumentId)
      throw const FormatException('Instrument binding changed.');
    return draft;
  }

  Future<M2Draft> save(
    M2Draft draft,
    String key,
    String state,
    Object? value, {
    String? marketplaceAssessmentId,
  }) async {
    if (marketplaceAssessmentId != null) _id(marketplaceAssessmentId);
    if (!draft.items.any((q) => q['item_key'] == key))
      throw const FormatException('Item is outside this M2 version.');
    await client.put(
      '/api/v1/m2/assessments/${draft.id}/answers/${Uri.encodeComponent(key)}',
      {
        'expected_revision': draft.revision,
        'answer_state': state,
        'value': value,
        if (marketplaceAssessmentId != null)
          'marketplace_assessment_id': marketplaceAssessmentId,
      },
    );
    final result = await read(draft.id);
    if (result.data['instrument']['id'] != draft.data['instrument']['id'] ||
        result.revision <= draft.revision) {
      throw const FormatException('Saved M2 revision could not be verified.');
    }
    return result;
  }

  Future<Map<String, dynamic>> action(
    M2Draft d,
    String action,
    Map<String, dynamic> body,
  ) {
    if (body.containsKey('expected_revision') ||
        action.contains('..') ||
        action.startsWith('/')) {
      throw ArgumentError('Reserved source revision or invalid M2 action.');
    }
    return client.post('/api/v1/m2/assessments/${d.id}/$action', {
      ...body,
      'expected_revision': d.revision,
    });
  }

  Future<Map<String, dynamic>> evaluate(M2Draft d) async {
    final result = await action(d, 'bdj/evaluate', {});
    if (result['assessment_id'] != d.id || result['revision'] != d.revision) {
      throw const FormatException('Stale BDJ source.');
    }
    return result;
  }

  Future<Map<String, dynamic>> decide(
    M2Draft d,
    String findingId,
    String decision,
    String requestId,
  ) async {
    _id(findingId);
    _id(requestId);
    if (!['KEEP_ORIGINAL', 'REVIEW_LATER'].contains(decision))
      throw ArgumentError('Invalid finding decision.');
    final result = await action(d, 'findings/$findingId/decisions', {
      'decision': decision,
      'request_id': requestId,
    });
    final event = result['event'] as Map<String, dynamic>;
    if (event['assessment_id'] != d.id ||
        event['assessment_revision'] != d.revision ||
        event['finding_id'] != findingId ||
        event['decision'] != decision ||
        event['request_id'] != requestId ||
        result['answer_changed'] != false ||
        result['finding_resolved'] != false) {
      throw const FormatException('Finding decision source mismatch.');
    }
    return result;
  }

  Future<Map<String, dynamic>> review(
    M2Draft d, {
    String? marketplaceAssessmentId,
  }) async {
    if (marketplaceAssessmentId != null) _id(marketplaceAssessmentId);
    final result = await action(d, 'review', {
      if (marketplaceAssessmentId != null)
        'marketplace_assessment_id': marketplaceAssessmentId,
    });
    if (result['assessment_id'] != d.id ||
        result['assessment_revision'] != d.revision ||
        !_uuid.hasMatch(result['id'] as String? ?? ''))
      throw const FormatException('Review source mismatch.');
    return result;
  }

  /// The exact terms the interface must show before asking for AI permission.
  ///
  /// The client never composes these: it displays what the server discloses and
  /// echoes it back unchanged. `build_consent` refuses any disagreement, so a
  /// locally invented term would be a refusal rather than a wider grant.
  Future<Map<String, dynamic>> aiProcessingDisclosure() async {
    final result =
        await client.get('/api/v1/m2/ai-processing-disclosure');
    if (result['contract_version'] is! String ||
        result['provider'] is! String ||
        result['purpose'] is! String ||
        result['endpoint'] is! String ||
        result['model'] is! String) {
      throw const FormatException('AI-processing disclosure is incomplete.');
    }
    return result;
  }

  Future<Map<String, dynamic>> confirm(
    M2Draft d,
    List<String> findingIds, {
    String? marketplaceAssessmentId,
    Map<String, dynamic>? aiProcessing,
  }) async {
    if (marketplaceAssessmentId != null) _id(marketplaceAssessmentId);
    final result = await action(d, 'confirm', {
      'acknowledged_issue_ids': findingIds,
      if (marketplaceAssessmentId != null)
        'marketplace_assessment_id': marketplaceAssessmentId,
      // Omitted, never false-by-default: absence and "declined" are different
      // records, and the server treats only an affirmative echo as a grant.
      if (aiProcessing != null) 'ai_processing': aiProcessing,
    });
    if (result['assessment_id'] != d.id ||
        result['assessment_revision'] != d.revision ||
        !_uuid.hasMatch(result['id'] as String? ?? '')) {
      throw const FormatException('Confirmation source mismatch.');
    }
    final snapshot = result['snapshot_json'] as Map<String, dynamic>;
    if (snapshot['assessment_id'] != d.id ||
        snapshot['assessment_revision'] != d.revision ||
        snapshot['qj_handoff_authorized'] != false ||
        result['snapshot_digest'] !=
            sha256
                .convert(utf8.encode(canonicalConfirmationJson(snapshot)))
                .toString()) {
      throw const FormatException(
        'Confirmation snapshot fingerprint mismatch.',
      );
    }
    return result;
  }

  Future<Map<String, dynamic>> confirmUncertainty(
    String confirmationId,
    String exactText,
  ) async {
    _id(confirmationId);
    final result = await client.post(
      '/api/v1/m2/confirmations/$confirmationId/uncertainty',
      {'exact_text': exactText},
    );
    if (result['confirmation_id'] != confirmationId ||
        !_uuid.hasMatch(result['id'] as String? ?? '') ||
        result['exact_text'] != exactText.trim())
      throw const FormatException('Uncertainty confirmation mismatch.');
    return result;
  }

  /// Creates a confirmed research objective against an existing confirmation.
  ///
  /// `origin` is `BDJ` (derived from a finding) or `ENTREPRENEUR`. The server
  /// pins the objective to the confirmation revision, so `expected_revision`
  /// must be the confirmation's own revision. The response is a persisted
  /// objective record; it does not authorize QJ execution.
  Future<Map<String, dynamic>> createObjective(
    String confirmationId,
    int expectedRevision,
    String objective, {
    String origin = 'ENTREPRENEUR',
    String? findingId,
  }) async {
    _id(confirmationId);
    if (findingId != null) _id(findingId);
    if (!['BDJ', 'ENTREPRENEUR'].contains(origin))
      throw ArgumentError('Invalid research objective origin.');
    final text = objective;
    if (text.trim().isEmpty)
      throw ArgumentError('Research objective is required.');
    final result = await client
        .post('/api/v1/m2/confirmations/$confirmationId/research-objectives', {
          'expected_revision': expectedRevision,
          'origin': origin,
          'objective': text,
          if (findingId != null) 'finding_id': findingId,
        });
    if (!_uuid.hasMatch(result['id'] as String? ?? '') ||
        result['confirmation_id'] != confirmationId)
      throw const FormatException('Research objective source mismatch.');
    return result;
  }

  /// Reads the existing owner-scoped workspace. The endpoint does not supply
  /// objective approval/version or BCB validity: callers must keep those held.
  Future<M2ResearchWorkspace> readResearchWorkspace(
    String assessmentId,
    String confirmationId,
    int expectedRevision,
  ) async {
    _id(assessmentId);
    _id(confirmationId);
    if (expectedRevision < 0)
      throw ArgumentError('A current revision is required.');
    final result = await client.get(
      '/api/v1/m2/confirmations/$confirmationId/research-workspace',
      query: {'expected_revision': '$expectedRevision'},
    );
    final rows = result['objectives'];
    if (rows is! List || rows.any((row) => row is! Map)) {
      throw const FormatException('Research workspace response is invalid.');
    }
    final parsed = <Map<String, dynamic>>[];
    for (final row in rows) {
      final record = Map<String, dynamic>.from(row as Map);
      if (!_uuid.hasMatch(record['id'] as String? ?? '') ||
          record['exact_text'] is! String ||
          record['provenance'] is! Map) {
        throw const FormatException('Research objective source is invalid.');
      }
      final source = record['provenance'] as Map;
      if (source['assessment_id'] != assessmentId ||
          source['confirmation_id'] != confirmationId ||
          source['assessment_revision'] != expectedRevision) {
        throw const FormatException(
          'Research objective source binding mismatch.',
        );
      }
      if (record['approval_status'] == 'CONFIRMED_BY_OWNER' &&
          (record['objective_version_id'] != record['id'] ||
              record['owner_decision'] != 'CONFIRMED' ||
              source['objective_version'] != record['id'] ||
              source['origin'] != 'ENTREPRENEUR')) {
        throw const FormatException('Research objective decision is invalid.');
