/// UI-07 — cross-language canonical JSON and snapshot digest equivalence.
///
/// The backend hashes with Python's
/// `json.dumps(value, sort_keys=True, ensure_ascii=False,
/// separators=(",", ":"), allow_nan=False)`
/// (`sitewise.project1.contracts.canonical` / `digest`,
/// `sitewise.services.business_context_v1.source_hash`, and the inline digest in
/// `sitewise.services.m2_service`). The Dart client recomputes those digests to
/// verify server responses.
///
/// `jsonEncode` is **not** byte-equivalent for doubles: it renders `1e-6` as
/// `0.000001` and `1e16` as `10000000000000000.0`, where Python renders `1e-06`
/// and `1e+16`. Before this test existed, a valid confirmation carrying such a
/// float threw `Confirmation snapshot fingerprint mismatch`.
///
/// `test/fixtures/m2_canonical_equivalence.json` is generated by the Python
/// implementation itself, so it is authoritative rather than a second Dart
/// reimplementation. Regenerate it with the script recorded in the fixture's
/// `generator` field whenever the Python canonicaliser changes.
library;

import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:shared_logic/shared_logic.dart';
import 'package:test/test.dart';

Map<String, dynamic> _loadFixture() {
  final file = File('test/fixtures/m2_canonical_equivalence.json');
  if (!file.existsSync()) {
    fail('Missing canonical equivalence fixture at ${file.path}.');
  }
  return jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
}

void main() {
  final doc = _loadFixture();
  final cases = (doc['cases'] as List).cast<Map<String, dynamic>>();

  group('canonical equivalence fixture', () {
    test('fixture is the expected contract and is non-trivial', () {
      expect(doc['contract'], 'm2-canonical-equivalence/1');
      expect(doc['case_count'], cases.length);
      // A fixture that silently shrank would weaken the proof.
      expect(cases.length, greaterThan(900));
      final kinds = cases.map((c) => c['kind']).toSet();
      expect(
        kinds,
        containsAll(<String>[
          'pow10',
          'random_bits',
          'threshold',
          'int',
          'string',
          'bool',
          'null',
          'list',
          'map',
          'snapshot',
        ]),
      );
    });

    test('Dart canonical JSON matches Python byte-for-byte for every case', () {
      final mismatches = <String>[];
      for (final c in cases) {
        final expected = c['canonical'] as String;
        final actual = canonicalSourceJson(c['value']);
        if (actual != expected) {
          mismatches.add('${c['kind']}: python=$expected dart=$actual');
        }
      }
      expect(
        mismatches,
        isEmpty,
        reason: '${mismatches.length} of ${cases.length} cases diverged:\n'
            '${mismatches.take(10).join('\n')}',
      );
    });

    test('Dart sha256 over canonical bytes matches the Python digest', () {
      final digests = cases.where((c) => c.containsKey('digest')).toList();
      expect(digests, isNotEmpty);
      for (final c in digests) {
        final actual = sha256
            .convert(utf8.encode(canonicalSourceJson(c['value'])))
            .toString();
        expect(actual, c['digest'], reason: 'digest mismatch for ${c['kind']}');
      }
    });
  });

  group('float formatting boundaries that jsonEncode gets wrong', () {
    // Each pair is (value, Python repr). These are the cases that made a valid
    // server response fail client-side verification.
    const pythonRepr = <(double, String)>[
      (1e-6, '1e-06'),
      (1e-7, '1e-07'),
      (1e-5, '1e-05'),
      (1e-4, '0.0001'),
      (1e15, '1000000000000000.0'),
      (1e16, '1e+16'),
      (1e17, '1e+17'),
      (1e20, '1e+20'),
      (1e21, '1e+21'),
      (100.0, '100.0'),
      (1.5, '1.5'),
      (0.1, '0.1'),
      (1 / 3, '0.3333333333333333'),
      (1234567890.123, '1234567890.123'),
      (5e-324, '5e-324'),
      (1.7976931348623157e308, '1.7976931348623157e+308'),
    ];

    test('matches Python repr for every boundary value', () {
      for (final (value, expected) in pythonRepr) {
        expect(canonicalSourceJson(value), expected, reason: 'value=$value');
      }
    });

    test('jsonEncode would have diverged (guards the regression)', () {
      // Documents the defect this fix removes: if a future change reverts to
      // jsonEncode, these assertions fail.
      expect(jsonEncode(1e-6), isNot('1e-06'));
      expect(jsonEncode(1e16), isNot('1e+16'));
      expect(canonicalSourceJson(1e-6), '1e-06');
      expect(canonicalSourceJson(1e16), '1e+16');
    });

    test('signed zero is preserved the way Python preserves it', () {
      expect(canonicalSourceJson(0.0), '0.0');
      expect(canonicalSourceJson(-0.0), '-0.0');
    });

    test('integers stay integers (Python int, not float)', () {
      expect(canonicalSourceJson(0), '0');
      expect(canonicalSourceJson(42), '42');
      expect(canonicalSourceJson(-9007199254740993), '-9007199254740993');
    });

    test('non-finite doubles are rejected, as allow_nan=False rejects them', () {
      expect(() => canonicalSourceJson(double.nan), throwsArgumentError);
      expect(() => canonicalSourceJson(double.infinity), throwsArgumentError);
      expect(() => canonicalSourceJson(double.negativeInfinity),
          throwsArgumentError);
    });
  });

  group('structural rules', () {
    test('object keys are sorted and separators are compact', () {
      expect(
        canonicalSourceJson({'b': 1, 'a': 2, 'A': 3}),
        '{"A":3,"a":2,"b":1}',
      );
    });

    test('nested containers keep Python ordering and escaping', () {
      final value = {
        'z': [
          {'b': null, 'a': true},
          [],
          {},
        ],
        'a': 'caf\u00e9 \u65e5\u672c\u8a9e',
      };
      expect(
        canonicalSourceJson(value),
        '{"a":"caf\u00e9 \u65e5\u672c\u8a9e","z":[{"a":true,"b":null},[],{}]}',
      );
    });

    test('control characters are escaped as Python escapes them', () {
      expect(canonicalSourceJson('a\u0000b'), '"a\\u0000b"');
      expect(canonicalSourceJson('a\nb'), '"a\\nb"');
      expect(canonicalSourceJson('a\tb'), '"a\\tb"');
      expect(canonicalSourceJson('a"b'), '"a\\"b"');
      expect(canonicalSourceJson('a\\b'), '"a\\\\b"');
    });

    test('non-string object keys are refused rather than silently coerced', () {
      expect(() => canonicalSourceJson({1: 'a'}), throwsArgumentError);
    });
  });

  group('snapshot digest verification path', () {
    // The shape produced by services/m2_service.py, including floats that the
    // old implementation rendered differently from Python.
    Map<String, dynamic> snapshot() => <String, dynamic>{
          'snapshot_contract_version': 'm2-snapshot/2',
          'assessment_id': '0f0a6f3e-1b2c-4d5e-8f90-a1b2c3d4e5f6',
          'assessment_revision': 3,
          'instrument_id': '50906385-072b-5cf1-9661-4d001898ffb8',
          'instrument_version': 'M2V1-20261114-1',
          'instrument_digest': 'b' * 64,
          'bdj_rule_version': 'BDJ-M2V1-0.1-CAND',
          'qj_handoff_authorized': false,
          'answer_revisions': [
            {
              'item_key': 'M2V1-02',
              'answer_revision_id': 'c' * 36,
              'item_version_id': 'd' * 36,
              'answer_state': 'ANSWERED',
              'value': ['DELIVERY'],
            },
          ],
          'uncertainty': {
            'confidence': 0.85,
            'threshold': 1e-6,
            'tolerance': 1e-5,
          },
        };

    test('a snapshot containing 1e-6 / 1e-5 now verifies', () {
      final snap = snapshot();
      final digest =
          sha256.convert(utf8.encode(canonicalSourceJson(snap))).toString();
      // Recompute the same way the client does in confirm(): a second pass must
      // be stable, and must not throw. The fixture asserts the Python value.
      expect(digest, hasLength(64));
      expect(
        sha256.convert(utf8.encode(canonicalSourceJson(snap))).toString(),
        digest,
      );
      expect(canonicalSourceJson(1e-6), '1e-06');
    });

    test('the fixture snapshot digests are reproduced exactly', () {
      final snapshots =
          cases.where((c) => c['kind'] == 'snapshot').toList();
      expect(snapshots, isNotEmpty);
      for (final c in snapshots) {
        expect(
          sha256.convert(utf8.encode(canonicalSourceJson(c['value']))).toString(),
          c['digest'],
        );
      }
    });
  });
}
