"""Generate the P1 cloud-explanation artifacts from the prompt module and registry.

Four artifacts, all derived rather than hand-written:

* ``PROJECT1_CLOUD_EXPLANATION_PROMPT_V1_CANDIDATE.md`` — the exact system text
  and its per-item rule, plus the fingerprint a request would cite;
* ``PROJECT1_CLOUD_EXPLANATION_REQUEST_CONTRACT.json`` — the typed request for
  one item, plus the field inventory;
* ``PROJECT1_CLOUD_EXPLANATION_TEST_MATRIX.json`` — one case per item with the
  permitted and prohibited claims the registry itself declares, plus the
  adversarial cases;
* ``PROJECT1_CLOUD_EXPLANATION_OFFLINE_RESULTS.json`` — written by the test run,
  not by this script.

Run from ``backend``:

    ./.venv/Scripts/python.exe scripts/build_cloud_explanation_prompt.py
"""
from __future__ import annotations

import json
from pathlib import Path

from sitewise.project1 import explanation_prompt as P
from sitewise.project1.explanation_contracts import BANNED_PHRASES, SCHEMA_VERSION
from sitewise.project1.explanation_registry import load_registry, raw_question

OUT = Path(__file__).resolve().parents[2] / 'deliverables'
ALL = [f'Q{n:02d}' for n in range(1, 14)]

#: Why each gated item cannot be explained today. Kept next to the generator so
#: the matrix cannot claim a fallback the registry does not support.
GATE_REASON = {
    'NOT_AUTHORIZED': 'instrument status blocks measurement; no approved construct authority',
    'BLOCKED_SOURCE': 'source or routing authority is unresolved; applicability is unknown',
    'MISSING_APPROVED_STIMULUS': 'the exact offer or stimulus is not approved for fielding',
    'MISSING_APPROVED_BANK': 'the response or feature bank is not approved',
}


def _entry(qid: str) -> dict:
    entry = raw_question(qid)
    if entry is None:
        raise SystemExit(f'registry has no entry for {qid}')
    return entry


def build_prompt_md() -> str:
    reg = load_registry()
    lines = [
        '# PROJECT1 — Cloud Explanation Module Prompt V1 Candidate',
        '',
        f'**Prompt version:** `{P.PROMPT_VERSION}`  ',
        f'**Output schema:** `{SCHEMA_VERSION}` (unchanged, 14 fields)  ',
        f'**Intended stage:** `{P.INTENDED_STAGE}` — **not registered**, see §6  ',
        f'**Registry:** `{reg.registry_version}` / `{reg.sha256[:16]}…`  ',
        f'**Core fingerprint (no item rule):** `{P.prompt_fingerprint(None)}`',
        '',
        '> This document is generated by `backend/scripts/build_cloud_explanation_prompt.py`.',
        '> Do not hand-edit: the prompt text lives in `explanation_prompt.py` and the',
        '> item-specific sentences come verbatim from the hash-pinned registry.',
        '',
        '---',
        '',
        '## 1. What the model is for, and what it is not for',
        '',
        'The cloud model **interprets verified evidence**. It never measures. EE-01',
        'remains the only source of a count, a denominator or a percentage, and the',
        'request carries `permitted_percentages: []` on every path because the',
        'instrument stores `percentage` as `NULL` behind `CHECK(percentage IS NULL)`.',
        '',
        'Authority: `NONE`. Producing this prompt grants nothing.',
        '',
        '---',
        '',
        '## 2. Core role',
        '',
        '```text',
        P.CORE_ROLE,
        '```',
        '',
        '---',
        '',
        '## 3. Core instruction',
        '',
        '```text',
        P.CORE_INSTRUCTION,
        '```',
        '',
        '---',
        '',
        '## 4. Response-kind rules',
        '',
        'One rule per registry `response_kind`. A kind with no rule raises',
        '`EXPLANATION_PROMPT_KIND_UNSUPPORTED` rather than being explained as if it',
        'were a single select.',
        '',
        '| Response kind | Rule |',
        '|---|---|',
    ]
    for kind, rule in P.KIND_RULE.items():
        lines.append(f'| `{kind}` | {rule} |')

    lines += [
        '',
        '---',
        '',
        '## 5. Question-specific rules (Q01–Q13)',
        '',
        'Every quoted sentence below is copied from the registry. The `QUESTION_RULE`',
        'block is appended to the core instruction for the item being explained.',
        '',
    ]
    for qid in ALL:
        entry = _entry(qid)
        lines += [
            f'### {qid} — `{entry["construct_id"]}` ({entry["response_kind"]})',
            '',
            f'- Instrument gate: `{entry["instrument_gate"] or "none"}`',
            f'- Report sections: {", ".join(entry["report_sections"]) or "none"}',
            f'- Covers an objective: `{str(entry["covers_objective"]).lower()}`',
            f'- Prompt fingerprint with this rule: `{P.prompt_fingerprint(entry)}`',
            '',
            '```text',
            P.question_rule(entry),
            '```',
            '',
        ]

    lines += [
        '---',
        '',
        '## 6. Why this prompt cannot be dispatched today',
        '',
        'Two independent governance controls, neither of which this work relaxed:',
        '',
        '1. `sitewise.project1.ledger._ALLOWED_STAGES` is `{BDJ, QJ, QG}`. There is no',
        '   `EXPLANATION` stage, so reserving an attempt raises',
        '   `MODEL_STAGE_UNREGISTERED`.',
        '2. `sitewise.project1.disclosure` registers adapters for `BDJ` and `QG` only.',
        '   No adapter can issue an authorization for the explanation stage, so',
        '   `require_current` has nothing to check against.',
        '',
        'A live call is therefore **structurally refused**, not merely unauthorised.',
        'See `PROJECT1_CLOUD_EXPLANATION_PROVIDER_PREFLIGHT.md`.',
        '',
        '---',
        '',
        '## 7. Prohibited output classes',
        '',
        'Stated in the instruction and enforced by the validator:',
        '',
    ]
    for item in P.PROHIBITED_OUTPUT_CLASSES:
        lines.append(f'- {item}')
    lines += [
        '',
        'Banned phrases, checked on a Unicode-normalised form so case, spacing,',
        'diacritic and homoglyph evasion cannot smuggle a conclusion through:',
        '',
    ]
    for phrase in BANNED_PHRASES:
        lines.append(f'- `{phrase}`')
    lines += [
        '',
        '---',
        '',
        '## 8. Reproduction',
        '',
        '```bash',
        'cd backend',
        './.venv/Scripts/python.exe scripts/build_cloud_explanation_prompt.py',
        './.venv/Scripts/python.exe tools/p2_isolated_test_runner_20261122.py \\',
        '    --db project1_disposable_app tests/project1/test_cloud_explanation_prompt.py',
        '```',
        '',
    ]
    return '\n'.join(lines)


def _sample_packet(qid: str) -> dict:
    """A request as the backend would build it for this item."""
    entry = _entry(qid)
    gate = entry['instrument_gate']
    refs = ['EXPLANATION_TEMPLATE_AUTHORITY_UNVERIFIED', 'REPORT_ADMISSION_REQUIRED', qid]
    if gate:
        refs.append(gate)
    return {
        'task_mode': 'CLAIM_EXPLANATION',
        'context_id': f'ctx-{qid}',
        'snapshot_id': f'snap-{qid}',
        'snapshot_hash': '0' * 64,
        'measurement_ruleset_id': f'{qid.lower()}-v1',
        'report_admission_references': refs,
        'reference_universe': refs,
        'question': {
            'question_id': qid,
            'instrument_gate': gate,
            'evidence_state': 'VALID_APPROVED',
            'effective_state': gate or 'VALID_APPROVED',
            'routing_resolved': entry['routing_resolved'],
            'report_sections': list(entry['report_sections']),
            'template_usable_for_substantive_report': False,
        },
    }


def build_request_contract() -> dict:
    reg = load_registry()
    samples = {}
    for qid in ALL:
        entry = _entry(qid)
        labels = {c['code']: c['label_en'] for c in entry['codes'] if c.get('label_en')}
        samples[qid] = P.build_request(entry, _sample_packet(qid), labels=labels,
                                       display_order=entry['display_order'])
    return {
        '_note': ('Generated by scripts/build_cloud_explanation_prompt.py. '
                  'A request is built by the backend and carries only the minimum '
                  'evidence needed to explain one item. No percentage is ever '
                  'supplied; no respondent-level field may appear.'),
        'request_schema_version': P.REQUEST_SCHEMA_VERSION,
        'prompt_version': P.PROMPT_VERSION,
        'output_schema_version': SCHEMA_VERSION,
        'registry_version': reg.registry_version,
        'registry_sha256': reg.sha256,
        'authority': 'NONE',
        'field_inventory': {
            'question_id': 'registry item id, never inferred',
            'question_version': 'snapshot question version',
            'snapshot_id': 'EE-01 snapshot identity',
            'snapshot_hash': 'EE-01 fingerprint; binds the explanation to its measurement',
            'evidence_context_hash': 'report_readbacks.context_hash; the chart↔explanation join key',
            'research_objective': 'the objective this item is proximate to, or null',
            'objective_proximity': 'declared proximity, never coverage',
            'covers_objective': 'always false today: no objective has an approved measure',
            'verified_facts': 'supplied aggregate facts only',
            'permitted_counts': 'the counts the model may restate',
            'permitted_percentages': 'always empty: the instrument stores percentage as NULL',
            'highest_options': 'precomputed leading options; the model may not invent one',
            'highest_options_tied': 'when true the model must say tied, not pick a winner',
            'approved_display_labels': 'draft labels, marked as drafts elsewhere',
            'display_order': 'presentation order; not a ranking',
            'ordinal_meaning': 'declared level mapping, empty for Q02/Q04/Q07/Q13',
            'mandatory_limitations': 'item limitation and coverage limitation, verbatim',
            'permitted_claim_ids': 'the evidence references the output may cite',
            'report_admission_references': 'why the section is held',
            'report_sections': 'the sections this item feeds',
            'instrument_gate': 'the governance block, if any',
            'evidence_state': 'what the data supports',
            'effective_state': 'gate when set, else state',
            'template_usable_for_substantive_report': 'always false today',
            'prohibited_output_classes': 'the explicit prohibition list',
            'language': 'en for V1',
            'authority': 'always NONE',
        },
        'refusal_codes': {
            'EXPLANATION_REQUEST_VERSION_MISMATCH': 'request schema version not recognised',
            'EXPLANATION_REQUEST_SCHEMA_MISMATCH': 'output schema version not recognised',
            'EXPLANATION_REQUEST_AUTHORITY_INVALID': 'authority must be NONE',
            'EXPLANATION_REQUEST_PERCENTAGE_FORBIDDEN': 'a percentage was supplied',
            'EXPLANATION_REQUEST_TASK_MODE_INVALID': 'task mode not in the adopted pair',
            'EXPLANATION_REQUEST_CONTEXT_MISSING': 'evidence context hash absent',
            'EXPLANATION_REQUEST_SNAPSHOT_MISSING': 'snapshot hash absent',
            'EXPLANATION_REQUEST_KIND_MISSING': 'item given without a response kind',
            'EXPLANATION_REQUEST_CONTAINS_ROW_LEVEL_FIELD': 'a respondent-level field appeared',
            'EXPLANATION_REQUEST_PACKET_INVALID': 'packet malformed or without a context id',
        },
        'samples': samples,
    }


