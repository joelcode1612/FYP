import os
import sys

from sqlalchemy import engine_from_config, pool

from alembic import context

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from sitewise.core.config import settings
from sitewise.db.session import engine
from sitewise.db.models import *  # noqa: F401,F403
from sqlmodel import SQLModel

config = context.config

target_metadata = SQLModel.metadata


def include_object(obj, name, type_, reflected, compare_to):
    # These are query mirrors of externally maintained tables. In particular,
    # their unmapped legacy-user FKs must never become autogenerated DROP DDL.
    if type_ == "table":
        model_table = compare_to if reflected and compare_to is not None else obj
        return not model_table.info.get("externally_managed")
    return True


def run_migrations_offline() -> None:
    url = settings.database_url
    context.configure(
        url=url, target_metadata=target_metadata, literal_binds=True,
        dialect_opts={"paramstyle": "named"}, include_object=include_object,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine
    with connectable.connect() as connection:
        context.configure(
            connection=connection, target_metadata=target_metadata,
            include_object=include_object,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
