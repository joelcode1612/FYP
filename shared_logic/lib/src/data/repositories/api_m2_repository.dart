  /// `POST /research-questions/{version}/owner-review`.
  ///
  /// Reuses the pre-existing route. The server decides authority: it records a
  /// decision only for an authorized reviewer and current candidate; the
  /// physical assignment constraint also applies to an owner review. The client validates only
  /// the values the route declares (`decision` enum and bounded rationale) so a
  /// malformed request never reaches the server.
  Future<Map<String, dynamic>> recordOwnerReview(
    String version,
    ResearchReviewAction action,
    String rationale,
  ) async {
    _id(version);
    final trimmed = rationale.trim();
    final text = trimmed.isEmpty ? 'No rationale provided by reviewer.' : trimmed;
    if (text.length > 1000) {
      throw ArgumentError('The review rationale is too long.');
    }
    final result = await client.post(
      '/api/v1/m2/research-questions/$version/owner-review',
      {'decision': action.wireCode, 'rationale': text},
    );
    final recorded = result['decision'];
    if (recorded != null && recorded != action.wireCode) {
      throw const FormatException('The recorded decision does not match.');
    }
    // The route returns the stored row; an authority flag must never be read as
    // a grant even if the response grows one.
    if (result['fielding_authorized'] == true ||
        result['scientific_acceptance'] == true) {
      throw const FormatException(
        'The review response reported an authority it cannot grant.',
      );
    }
    return result;
  }

