"""Registry-backed deterministic explanation templates for Q01–Q13.

This module is the *only* consumer of ``q01_q13_explanation_registry.json``. It
holds no prose of its own: every substantive sentence it emits is read from that
file, which is generated by ``scripts/build_explanation_registry.py`` from the
owner-prepared handoff and the frozen instrument. There is deliberately no Dart
counterpart, because explanations are rendered on the server and shipped as text.

Three responsibilities, each kept small and independently testable:

``load_registry``
    Read and verify the pinned file. The SHA-256 is pinned in this module, so
    changing a single character of template prose requires editing a constant —
    a change that shows up in review. A stale pin fails closed.

``decide_state``
    Turn EE-01 counts plus the item's contract status into exactly one of twelve
    evidence states. Governance and data are separate axes, so an instrument block
    never conceals a data condition and all twelve states stay reachable.

``render_question``
    Compose the six ``ExplanationOutput`` prose fields from quoted template text.
    Nothing is computed here: counts and denominators arrive already measured, and
    a placeholder that cannot be filled from server-held data is a refusal, not a
    guess.

No function in this module grants authority. ``authority`` is always the caller's
to establish, and it never is.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from sitewise.domain.cq_runtime import CqRefused

REGISTRY_VERSION = 'q01-q13-explanation/1'

#: Pinned SHA-256 of the runtime registry. Regenerate with
#: ``scripts/build_explanation_registry.py``; that script prints the new value.
#:
#: History:
#:   bab9c409…  pre-CX-17-repair (labels carried the cp1252 en-dash mis-decode)
#:   416fc02e…  CX-17 repaired at source in QUESTION_CONTRACT_MATRIX.json
#:   f9b8dd2e…  CX-19 (wording e-acute) repaired at source
#:   427c504d…  CX-19 registered in the conflict register (19 conflicts)
#:   64d0d074…  display_order / ordinal_meaning provenance recorded per item
EXPECTED_REGISTRY_SHA256 = '64d0d074899e18959c66e450af34ee223d431962c492e026cd7add04cea84144'

REGISTRY_PATH = Path(__file__).with_name('data') / 'q01_q13_explanation_registry.json'

#: Instrument gates, in resolution order. The first one that applies wins, and it
#: outranks every data condition because the item cannot be measured at all.
INSTRUMENT_GATES = (
    'NOT_AUTHORIZED',
    'BLOCKED_SOURCE',
    'MISSING_APPROVED_STIMULUS',
    'MISSING_APPROVED_BANK',
)

#: Data states, in resolution order. Most specific first: an empty admissible set
#: is reported as such rather than as a refusal, and a small base is only reported
#: once there is a base.
EVIDENCE_STATES = (
    'WITHDRAWN_OR_NO_CONSENT',
    'NO_ADMISSIBLE_RESPONSES',
    'NOT_SHOWN_APPROVED_ROUTE',
    'UNKNOWN_ROUTE',
    'NON_SUBSTANTIVE_ONLY',
    'REFUSED_OR_CANNOT_JUDGE',
    'LOW_VALID_BASE',
    'VALID_APPROVED',
)

ALL_STATES = INSTRUMENT_GATES + EVIDENCE_STATES

#: How a snapshot was matched to an item. Recorded so a caller can tell a verified
#: assignment from a string derivation; only the former is authoritative.
RESOLUTION_BASES = ('VERIFIED_ASSIGNMENT', 'DERIVED_FROM_SLOT_ID', 'EXPLICIT_QUESTION_ID')

_PLACEHOLDER_ORDER = ('question_id', 'count', 'shown', 'V', 'feature', 'V_feature',
                      'category', 'percent', 'yes_count', 'yes_percent')


@dataclass(frozen=True)
class Template:
    template_id: str
    text: str
    placeholders: tuple[str, ...]


@dataclass(frozen=True)
class QuestionEntry:
    question_id: str
    construct_id: str
    instrument_status: str
    instrument_gate: str | None
    routing_resolved: bool
    response_kind: str
    substantive_codes: tuple[str, ...]
    codes: tuple[str, ...]
    #: Draft EN option labels keyed by code. Never approved wording; the chart
    #: marks them ``CONTRACT_OPTION_BANK_DRAFT`` when it presents one.
    labels: dict[str, str]
    withheld: Template
    valid: Template
    limitation: Template
    permitted_claim: str
    prohibited_inference: str
    coverage_limitation: str
    report_sections: tuple[str, ...]
    #: The section-level admission requirement, per assigned section, as CUST03
    #: declares it. Read-only; this module never evaluates admission.
    report_admission: dict
    template_usable_for_substantive_report: bool


@dataclass(frozen=True)
class Registry:
    registry_version: str
    sha256: str
    instrument_version: str
    instrument_sha256: str
    questions: dict[str, QuestionEntry]
    state_templates: dict[str, str | None]
    framing: dict
    literals: frozenset[str]

    def question(self, question_id: str) -> QuestionEntry | None:
        return self.questions.get(question_id)


def _verify(path: Path) -> bytes:
    if not path.exists():
        raise CqRefused('EXPLANATION_REGISTRY_MISSING', 503)
    raw = path.read_bytes()
    actual = hashlib.sha256(raw).hexdigest()
    if actual != EXPECTED_REGISTRY_SHA256:
        raise CqRefused('EXPLANATION_REGISTRY_HASH_MISMATCH', 503)
    return raw


@lru_cache(maxsize=1)
def load_registry() -> Registry:
    """Load and verify the pinned registry. Cached; the file is immutable."""
    raw = _verify(REGISTRY_PATH)
    payload = json.loads(raw)
    if payload.get('registry_version') != REGISTRY_VERSION:
        raise CqRefused('EXPLANATION_REGISTRY_VERSION_MISMATCH', 503)

    questions: dict[str, QuestionEntry] = {}
    for raw_q in payload['questions']:
        tmpl = raw_q['templates']
        questions[raw_q['question_id']] = QuestionEntry(
            question_id=raw_q['question_id'],
            construct_id=raw_q['construct_id'],
            instrument_status=raw_q['instrument_status'],
            instrument_gate=raw_q['instrument_gate'],
            routing_resolved=bool(raw_q['routing_resolved']),
            response_kind=raw_q['response_kind'],
            substantive_codes=tuple(raw_q['substantive_codes']),
            codes=tuple(c['code'] for c in raw_q['codes']),
            labels={c['code']: c['label_en'] for c in raw_q['codes'] if c.get('label_en')},
            withheld=Template(tmpl['withheld']['template_id'],
                              tmpl['withheld']['text'],
                              tuple(tmpl['withheld']['placeholders'])),
            valid=Template(tmpl['valid']['template_id'],
                           tmpl['valid']['text'],
                           tuple(tmpl['valid']['placeholders'])),
            limitation=Template(tmpl['limitation']['template_id'],
                                tmpl['limitation']['text'],
                                tuple(tmpl['limitation']['placeholders'])),
            permitted_claim=raw_q['permitted_claim'],
            prohibited_inference=raw_q['prohibited_inference'],
            coverage_limitation=raw_q['coverage_limitation'],
            report_sections=tuple(raw_q['report_sections']),
            report_admission=dict(raw_q['report_admission']),
            template_usable_for_substantive_report=bool(
                raw_q['template_usable_for_substantive_report']),
        )

    return Registry(
        registry_version=payload['registry_version'],
        sha256=hashlib.sha256(raw).hexdigest(),
        instrument_version=payload['instrument_version'],
        instrument_sha256=payload['instrument_sha256'],
        questions=questions,
        state_templates=payload['state_templates'],
        framing=payload['framing'],
        literals=_derive_literals(questions, payload['state_templates'], payload['framing']),
    )


@lru_cache(maxsize=1)
def _raw_payload() -> dict:
    """The verified registry exactly as written, parsed once."""
    return json.loads(_verify(REGISTRY_PATH))


def raw_question(question_id: str) -> dict | None:
    """One registry entry as written, or ``None`` if the item is not registered.

    ``QuestionEntry`` deliberately carries only what the renderer needs. Prompt
    composition also needs the declared fields it omits — ``ordinal_meaning``,
    ``display_order``, ``research_objective``, ``objective_proximity``,
    ``covers_objective`` and the per-code labels. Reading the same verified bytes
    keeps the hash pin in force rather than opening a second, unchecked path.
    """
    for raw_q in _raw_payload()['questions']:
        if raw_q.get('question_id') == question_id:
            return raw_q
    return None


def resolve_question(registry: Registry, *, question_id: str | None = None,
                     slot_id: str | None = None) -> tuple[QuestionEntry | None, str]:
    """Match a snapshot to an item, and say how.

    A verified assignment is authoritative. A slot id is accepted only because the
    manifest builder derives slots from question ids, and the derivation is
    labelled so a caller can see it is weaker. Anything else returns ``None`` and
    the caller must fall back to the generic explanation rather than guess.
    """
    if question_id:
        entry = registry.question(question_id)
        return (entry, 'EXPLICIT_QUESTION_ID') if entry else (None, 'UNRESOLVED')
    if not slot_id:
        return None, 'UNRESOLVED'
    if slot_id.startswith('Q10:'):
        # A per-feature Q10 slot. EE-01 has no per-feature denominator (CX-11), so
        # this is a known-unsupported shape, not an unknown one.
        return None, 'PER_FEATURE_SLOT_UNSUPPORTED'
    entry = registry.question(slot_id)
    return (entry, 'DERIVED_FROM_SLOT_ID') if entry else (None, 'UNRESOLVED')


def decide_state(entry: QuestionEntry, *, q: int, s: int, a: int, v: int,
                 refused: int = 0, invalid: int = 0, excluded: int = 0,
                 total_units: int | None = None,
                 floor: int | None = None) -> tuple[str, str]:
    """Return ``(gate_or_none, evidence_state)`` for one item and one snapshot.

    Both axes are always evaluated. ``gate`` is the instrument block, if any;
    ``state`` describes what the data supports. The caller reports the gate when it
    is set and the state otherwise, but the state is never hidden from the record.
    """
    if q < 0 or v < 0 or a < 0 or s < 0:
        raise CqRefused('EXPLANATION_COUNTS_INVALID', 503)
    if not (v <= a <= s <= q):
        raise CqRefused('EXPLANATION_COUNTS_NOT_MONOTONIC', 503)

    gate = entry.instrument_gate

    # --- data axis, most specific first -----------------------------------
    if q == 0:
        if total_units is not None and total_units > 0 and excluded >= total_units:
            return gate, 'WITHDRAWN_OR_NO_CONSENT'
        return gate, 'NO_ADMISSIBLE_RESPONSES'
    if s == 0:
        return gate, 'NOT_SHOWN_APPROVED_ROUTE'
    if not entry.routing_resolved:
        # The show gate itself is unadopted, so "was it presented?" has no verified
        # answer. This outranks the refusal counts: an unverified applicability
        # cannot be reported as a refusal.
        return gate, 'UNKNOWN_ROUTE'
    if v == 0:
        if refused + invalid > 0:
            return gate, 'REFUSED_OR_CANNOT_JUDGE'
        return gate, 'NON_SUBSTANTIVE_ONLY'
    if floor is not None and v <= floor:
        return gate, 'LOW_VALID_BASE'
    return gate, 'VALID_APPROVED'


def effective_state(gate: str | None, state: str) -> str:
    """The single state a caller reports: the gate when set, else the data state."""
    return gate or state


def state_label(registry: Registry, state: str) -> str:
    labels = registry.framing['state_labels']
    if state not in labels:
        raise CqRefused('EXPLANATION_STATE_UNKNOWN', 503)
    return labels[state]


def state_sentence(registry: Registry, state: str, *, question_id: str,
                   count: int | None = None, shown: int | None = None,
                   v: int | None = None) -> str:
    """Fill an owner-prepared state sentence. Missing figures are a refusal.

    A sentence that needs a number is never emitted without it: the alternative is
    a sentence with a hole, which reads as a measurement.
    """
    text = registry.state_templates.get(state)
    if text is None:
        raise CqRefused('EXPLANATION_STATE_TEMPLATE_ABSENT', 503)
    values = {'question_id': question_id, 'count': count, 'shown': shown, 'V': v}
    out = text
    for placeholder in _PLACEHOLDER_ORDER:
        token = '{' + placeholder + '}'
        if token not in out:
            continue
        value = values.get(placeholder)
        if value is None:
            raise CqRefused('EXPLANATION_TEMPLATE_FIGURE_MISSING', 503)
        out = out.replace(token, str(value))
    return out


def fill_item_template(template: Template, values: dict) -> str:
    """Fill an item template, refusing on any placeholder the caller cannot supply."""
    out = template.text
    for placeholder in template.placeholders:
        token = '{' + placeholder + '}'
        if token not in out:
            continue
        value = values.get(placeholder)
        if value is None:
            raise CqRefused('EXPLANATION_TEMPLATE_FIGURE_MISSING', 503)
        out = out.replace(token, str(value))
    if '{' in out:
        # A brace survived, so the template declares a placeholder the registry did
        # not enumerate. Fail rather than ship a half-filled sentence.
        raise CqRefused('EXPLANATION_TEMPLATE_PLACEHOLDER_UNDECLARED', 503)
    return out


def _derive_literals(questions: dict[str, QuestionEntry],
                     state_templates: dict[str, str | None],
                     framing: dict) -> frozenset[str]:
    """Every numeral and quantity word the pinned registry legitimately contains.

    The narrative guard rejects unsourced numerals and all quantity words, which is
    correct for model output but would reject the owner's own prose (``30``,
    ``100``, ``344``, ``Four``, ``two``). This set is the narrow allowance: a token
    is accepted in template prose only when it appears verbatim here, and the
    allowance is derived from a hash-pinned file rather than from the caller.
    """
    from sitewise.project1.explanation_contracts import _NUMBER_RE, _QUANTITY_WORD_RE

    parts: list[str] = []
    for entry in questions.values():
        parts.extend((entry.withheld.text, entry.valid.text, entry.limitation.text,
                      entry.permitted_claim, entry.prohibited_inference,
                      entry.coverage_limitation))
    for text in state_templates.values():
        if text:
            parts.append(text)
    parts.extend(str(v) for v in framing.values() if isinstance(v, str))
    parts.extend(str(v) for v in framing.get('state_labels', {}).values())
    blob = '\n'.join(parts)

    tokens: set[str] = set()
    tokens.update(_NUMBER_RE.findall(blob))
    tokens.update(word.lower() for word in _QUANTITY_WORD_RE.findall(blob))
    return frozenset(tokens)


def render_question(registry: Registry, entry: QuestionEntry, *,
                    gate: str | None, state: str, question_id: str,
                    figures: dict | None = None, missing: list[str] | None = None) -> dict:
    """Compose the six prose fields for one item in one state.

    ``figures`` is only consulted for ``VALID_APPROVED``; every other state is
    deliberately value-free, so a withheld result cannot leak a count through
    narrative. Returns a mapping ready for ``ExplanationOutput``.
    """
    frame = registry.framing
    state = effective_state(gate, state)
    if state not in ALL_STATES:
        raise CqRefused('EXPLANATION_STATE_UNKNOWN', 503)

    label = state_label(registry, state)
    headline = frame['headline'].format(question_id=question_id, state_label=label)

    if state == 'VALID_APPROVED':
        values = dict(figures or {})
        observation = fill_item_template(entry.valid, values)
        research = frame['research_permitted_prefix'].format(question_id=question_id)
        research += entry.permitted_claim
        planning = frame['planning_valid']
        summary = frame['summary_valid'].format(question_id=question_id)
        insufficient = False
    else:
        sentence = state_sentence(registry, state, question_id=question_id,
                                  count=(figures or {}).get('count'),
                                  shown=(figures or {}).get('shown'),
                                  v=(figures or {}).get('V'))
        observation = ' '.join(filter(None, (sentence, entry.withheld.text)))
        research = frame['research_no_claim'].format(question_id=question_id)
        planning = frame['planning_withheld']
        summary = frame['summary_withheld'].format(question_id=question_id)
        insufficient = True

    limitations = ' '.join((
        frame['limitation_prefix'] + entry.limitation.text,
        frame['limitation_coverage_prefix'] + entry.coverage_limitation,
    ))

    return {
        'headline': headline,
        'observation_interpretation': observation,
        'research_interpretation': research,
        'planning_implication': planning,
        'limitations': limitations,
        'summary': summary,
        'insufficient_evidence': insufficient,
        'missing_evidence_references': list(missing or []),
        'state': state,
        'gate': gate,
        'question_id': question_id,
        'registry_version': registry.registry_version,
        'registry_sha256': registry.sha256,
        'templates_used': (
            [entry.valid.template_id] if state == 'VALID_APPROVED'
            else [entry.withheld.template_id, entry.limitation.template_id]),
    }
