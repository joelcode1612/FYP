  //
  // The routes live in `backend/src/sitewise/api/v1/qg_candidate.py` and the
  // pre-existing owner-review route in `m2.py`. Transport only: what a payload
  // means and which actions a status allows live in
  // `domain/entities/research_candidate.dart`, shared by both apps.

  /// `POST /research-objectives/{objective_id}/qg-candidate`.
  ///
  /// Documented refusals are RETURNED, not thrown, because they are expected
  /// answers the UI renders differently:
  ///
  /// * 409 -> [CandidateOutcomeKind.conflict] (stale revision / context mismatch)
  /// * 429 -> [CandidateOutcomeKind.budgetExhausted]
  /// * 503 -> [CandidateOutcomeKind.unavailable] (runner missing, engine failure)
  ///
  /// A 401/403 is rethrown so the app's normal session handling runs. The
  /// caller must not treat a non-validated outcome as "no question exists".
  Future<CandidatePrepareOutcome> prepareCandidate({
    required String objectiveId,
    required int expectedRevision,
    required String contextId,
  }) => _candidateCall(
    '/api/v1/m2/research-objectives/$objectiveId/qg-candidate',
    objectiveId: objectiveId,
    expectedRevision: expectedRevision,
    contextId: contextId,
  );

  /// `POST /research-questions/{version}/revision`.
  ///
  /// The server refuses unless the parent's terminal decision was
  /// REQUEST_REVISION (409 `QG_CANDIDATE_REVISION_NOT_REQUESTED`) and refuses a
  /// byte-identical child (409 `QG_CANDIDATE_REVISION_UNCHANGED`). Both come
  /// back as a conflict outcome, never as a silent success.
  Future<CandidatePrepareOutcome> reviseCandidate({
    required String version,
    required int expectedRevision,
    required String contextId,
  }) => _candidateCall(
    '/api/v1/m2/research-questions/$version/revision',
    version: version,
    expectedRevision: expectedRevision,
    contextId: contextId,
  );

  Future<CandidatePrepareOutcome> _candidateCall(
    String path, {
    required int expectedRevision,
    required String contextId,
    String? objectiveId,
    String? version,
  }) async {
    if (objectiveId != null) _id(objectiveId);
    if (version != null) _id(version);
    _id(contextId);
    if (expectedRevision < 0) {
      throw ArgumentError('A non-negative source revision is required.');
    }
    try {
      final body = await client.post(path, {
        'expected_revision': expectedRevision,
        'context_id': contextId,
      });
      return CandidatePrepareOutcome.fromAnswer(body);
    } on UnauthorizedFailure {
      rethrow;
    } on AppFailure catch (failure) {
      return CandidatePrepareOutcome.fromFailure(failure);
    }
  }

